#!/usr/bin/env python3
"""Validate re_nilm detectors against reference detection scripts on N customers.

For each technology (PV, AC, HP, Battery, EV), runs both the reference and the
current re_nilm detection logic on the same randomly sampled customers and
reports binary classification agreement. Target: >= 95% agreement per technology.

EV has no reference Python script (original source was a notebook). Sanity
checks are run instead: probability in [0, 1], session counts non-negative.

The reference detection scripts are imported from ``old_files/model/`` and
``old_files/hp_model/``, which are added to sys.path automatically.

Prerequisites:
    - Smart meter parquet files at ``--data-dir``.
    - Weather parquet generated by a prior pipeline run (see ``--weather``).
      The pipeline writes this to the results directory as
      ``weather_<backend>_<start>_<end>.parquet`` — check ``data/processed/out/``
      for the exact filename.
    - Pre-trained model artifacts in ``models/`` (ac_detector_v1.joblib,
      hp_detector_v1.joblib). Run ``train_models.py`` first if missing.

Output:
    CSV report at the path given by ``--output`` (default: validation_report.csv).
    A summary table is also printed to stdout.

Usage:
    python scripts/validate_detectors.py \\
        --data-dir data/re_data/ETHZ_ALL \\
        --weather data/processed/out/weather_meteoswiss_None_None.parquet \\
        --n-customers 50 \\
        --seed 42 \\
        --output validation_report.csv
"""

from __future__ import annotations

import argparse
import logging
import random
import sys
from pathlib import Path
from typing import Dict, List, Optional

import joblib
import numpy as np
import pandas as pd

_REPO = Path(__file__).resolve().parents[1]
_MODEL_DIR = _REPO / "old_files" / "model"
_HP_MODEL_DIR = _REPO / "old_files" / "hp_model"
for _p in [str(_REPO), str(_MODEL_DIR), str(_HP_MODEL_DIR)]:
    if _p not in sys.path:
        sys.path.insert(0, _p)

