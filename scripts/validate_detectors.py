def _run_new_detectors(
    customers: Dict[str, pd.DataFrame],
    weather_df: pd.DataFrame,
    models_dir: Path,
) -> Dict[str, Dict[str, dict]]:
    """Run all new detectors on each customer. Returns {technology: {cid: result}}."""
    pv_det = PVDetector()
    ev_det = EVDetector()

    ac_model_path = models_dir / "ac_detector_v1.joblib"
    hp_model_path = models_dir / "hp_detector_v1.joblib"
    ac_det = ACDetector.load(ac_model_path) if ac_model_path.exists() else None
    hp_det = HeatPumpDetector.load(hp_model_path) if hp_model_path.exists() else None
    batt_det = BatteryDetector()

    new_pv, new_ac, new_hp, new_batt, new_ev = {}, {}, {}, {}, {}

    for cid, df in customers.items():
        r_pv = pv_det.predict_customer(df, weather_df)
        if r_pv:
            new_pv[cid] = r_pv

        if ac_det:
            try:
                r_ac = ac_det.predict_customer(df, weather_df)
                if r_ac:
                    new_ac[cid] = r_ac
            except Exception as exc:
                log.debug("New AC failed for %s: %s", cid, exc)

        if hp_det:
            try:
                r_hp = hp_det.predict_customer(df, weather_df)
                if r_hp:
                    new_hp[cid] = r_hp
            except Exception as exc:
                log.debug("New HP failed for %s: %s", cid, exc)

        r_batt = batt_det.predict_customer(df, weather_df, pv_result=new_pv.get(cid))
        if r_batt:
            new_batt[cid] = r_batt

        r_ev = ev_det.predict_customer(df, weather_df)
        if r_ev:
            new_ev[cid] = r_ev

    return {
        "pv": new_pv,
        "ac": new_ac,
        "hp": new_hp,
        "battery": new_batt,
        "ev": new_ev,
    }


# ---------------------------------------------------------------------------
# Comparison helpers
# ---------------------------------------------------------------------------

def _compare_binary(
    old: Dict[str, dict],
    new: Dict[str, dict],
    technology: str,
    old_flag: str,
    new_flag: str,
    old_prob: Optional[str],
    new_prob: Optional[str],
) -> pd.DataFrame:
    common = set(old) & set(new)
    if not common:
        log.warning("[%s] No overlapping customers between old and new — skipping", technology)
        return pd.DataFrame()
    rows = []
    for cid in sorted(common):
        o, n = old[cid], new[cid]
        old_val = bool(o.get(old_flag, False))
        new_val = bool(n.get(new_flag, False))
        row = {
            "technology": technology,
            "customer_id": cid,
            "old_pred": old_val,
            "new_pred": new_val,
            "agreement": old_val == new_val,
        }
        if old_prob:
            row["old_prob"] = round(float(o.get(old_prob, np.nan)), 4)
        if new_prob:
            row["new_prob"] = round(float(n.get(new_prob, np.nan)), 4)
        if old_prob and new_prob:
            row["prob_delta"] = round(row["new_prob"] - row["old_prob"], 4)
        rows.append(row)
    return pd.DataFrame(rows)


def _sanity_ev(new_ev: Dict[str, dict]) -> pd.DataFrame:
    rows = []
    for cid, r in new_ev.items():
        prob = float(r.get("prob_ev", np.nan))
        sessions = int(r.get("ev_total_sessions", -1))
        yearly = float(r.get("ev_yearly_mwh", np.nan))
        sanity_ok = (
            0.0 <= prob <= 1.0
            and sessions >= 0
            and yearly >= 0.0
        )
        rows.append({
            "technology": "ev",
            "customer_id": cid,
            "new_pred": bool(r.get("has_ev", False)),
            "prob_ev": round(prob, 4),
            "ev_total_sessions": sessions,
            "ev_yearly_mwh": round(yearly, 2),
            "sanity_ok": sanity_ok,
        })
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Summary printer
# ---------------------------------------------------------------------------

def _print_summary(report: pd.DataFrame) -> None:
    print("\n" + "=" * 60)
    print("VALIDATION SUMMARY")
    print("=" * 60)

    for tech, grp in report.groupby("technology"):
        if "agreement" in grp.columns and grp["agreement"].notna().any():
            n = len(grp)
            n_agree = int(grp["agreement"].sum())
            pct = 100.0 * n_agree / n if n else 0.0
            status = "✓ PASS" if pct >= 95 else "✗ FAIL"
            print(f"  {tech:10s}  {n_agree:3d}/{n:3d} agree  ({pct:.1f}%)  {status}")
            if "prob_delta" in grp.columns:
                med_delta = grp["prob_delta"].abs().median()
                print(f"             median |prob_delta| = {med_delta:.4f}")
        elif tech == "ev" and "sanity_ok" in grp.columns:
            n = len(grp)
            n_ok = int(grp["sanity_ok"].sum())
            pct = 100.0 * n_ok / n if n else 0.0
            status = "✓ PASS" if pct == 100 else "✗ FAIL"
            print(f"  {'ev':10s}  {n_ok:3d}/{n:3d} sane   ({pct:.1f}%)  {status}  [sanity only]")

    print("=" * 60 + "\n")


