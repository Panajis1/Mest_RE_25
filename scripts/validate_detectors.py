def main() -> None:
    parser = argparse.ArgumentParser(description="Validate re_nilm detectors vs legacy scripts")
    parser.add_argument("--data-dir", required=True, type=Path, help="Directory with RE parquet files")
    parser.add_argument("--weather", required=True, type=Path, help="Path to weather_cache.parquet")
    parser.add_argument("--n-customers", type=int, default=50, help="Number of customers to sample")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for customer sampling")
    parser.add_argument("--output", type=Path, default=Path("validation_report.csv"))
    parser.add_argument("--models-dir", type=Path, default=Path("models"))
    args = parser.parse_args()

    # Resolve paths relative to repo root when run from any directory
    data_dir = (args.data_dir if args.data_dir.is_absolute() else _REPO / args.data_dir)
    weather_path = (args.weather if args.weather.is_absolute() else _REPO / args.weather)
    models_dir = (args.models_dir if args.models_dir.is_absolute() else _REPO / args.models_dir)

    log.info("Loading weather from %s", weather_path)
    weather_df = _load_weather(weather_path)

    log.info("Building customer index from %s", data_dir)
    index = build_customer_file_index(data_dir)
    all_ids = sorted(index.keys())
    if not all_ids:
        raise RuntimeError(f"No customers found in {data_dir}")

    rng = random.Random(args.seed)
    sample_ids = rng.sample(all_ids, min(args.n_customers, len(all_ids)))
    log.info("Sampled %d customers (seed=%d)", len(sample_ids), args.seed)

    log.info("Loading customer data...")
    customers: Dict[str, pd.DataFrame] = {}
    for cid in sample_ids:
        df = load_customer_from_index(cid, index)
        if not df.empty:
            customers[cid] = df
    log.info("Loaded %d non-empty customers", len(customers))

    # --- New detectors ---
    log.info("Running new re_nilm detectors...")
    new_results = _run_new_detectors(customers, weather_df, models_dir)

    # --- Old detectors ---
    log.info("Running old PV detection (batch)...")
    old_pv = _old_pv_batch(customers, weather_df)

    log.info("Running old AC detection (per customer)...")
    old_ac = _old_ac_batch(customers, weather_df)

    log.info("Running old HP detection (per customer)...")
    old_hp = _old_hp_batch(customers, weather_df)

    log.info("Running old Battery detection (per customer)...")
    old_batt = _old_battery_per_customer(customers, weather_df, new_results["pv"])

    # --- Comparisons ---
    frames: List[pd.DataFrame] = []

    df_pv = _compare_binary(old_pv, new_results["pv"], "pv", "has_pv", "has_pv", "has_pv_prob", "prob_pv")
    frames.append(df_pv)

    if old_ac and new_results["ac"]:
        df_ac = _compare_binary(old_ac, new_results["ac"], "ac", "has_ac", "has_ac", "prob_ac", "prob_ac")
        frames.append(df_ac)
    else:
        log.warning("AC comparison skipped (old=%d new=%d customers)", len(old_ac), len(new_results["ac"]))

    if old_hp and new_results["hp"]:
        df_hp = _compare_binary(old_hp, new_results["hp"], "hp", "has_hp", "has_hp", "prob_hp", "prob_hp")
        frames.append(df_hp)
    else:
        log.warning("HP comparison skipped (old=%d new=%d customers)", len(old_hp), len(new_results["hp"]))

    if old_batt and new_results["battery"]:
        df_batt = _compare_binary(old_batt, new_results["battery"], "battery", "has_battery", "has_battery", "prob_battery", "prob_battery")
        frames.append(df_batt)
    else:
        log.warning("Battery comparison skipped")

    if new_results["ev"]:
        df_ev = _sanity_ev(new_results["ev"])
        frames.append(df_ev)

    if not frames:
        log.error("No comparison data generated — check data paths and model files")
        sys.exit(1)

    report = pd.concat(frames, ignore_index=True)
    output_path = (args.output if args.output.is_absolute() else _REPO / args.output)
    report.to_csv(output_path, index=False)
    log.info("Report saved → %s", output_path)

    _print_summary(report)


if __name__ == "__main__":
    main()
