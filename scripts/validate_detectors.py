def _old_pv_batch(customers: Dict[str, pd.DataFrame], weather_df: pd.DataFrame) -> Dict[str, dict]:
    """Run old pv_detection batch logic on all loaded customers."""
    from pv_detection import (
        compute_daily_weather,
        build_customer_daily_features,
        compute_pv_indicators,
        classify_pv_customers,
    )

    weather_idx = _weather_indexed(weather_df)

    frames = []
    for cid, df in customers.items():
        d = df.copy()
        d["DT_UTC"] = pd.to_datetime(d["DT_UTC"], errors="coerce").astype("datetime64[us]")
        d["ID"] = cid
        frames.append(d)
    if not frames:
        return {}
    re_data = pd.concat(frames, ignore_index=True)

    # Merge global_rad_W from indexed weather
    re_data = re_data.sort_values("DT_UTC")
    weather_reset = weather_idx[["global_rad_W"]].rename_axis("DT_UTC").reset_index()
    weather_reset["DT_UTC"] = weather_reset["DT_UTC"].astype("datetime64[us]")
    re_data_with_meteo = pd.merge_asof(
        re_data,
        weather_reset,
        on="DT_UTC",
        direction="backward",
        tolerance=pd.Timedelta("1h"),
    )

    daily_weather = compute_daily_weather(weather_idx)
    daily_features = build_customer_daily_features(re_data_with_meteo, daily_weather)

    pv_indicators = compute_pv_indicators(daily_features, re_data_with_meteo)
    if pv_indicators.empty:
        return {}
    pv_classified = classify_pv_customers(pv_indicators)

    results = {}
    for _, row in pv_classified.iterrows():
        cid = str(row["customer_id"])
        results[cid] = {
            "has_pv": bool(row.get("has_pv", False)),
            "has_pv_prob": float(row.get("has_pv_prob", np.nan)),
            "corr_prod_rad": float(row.get("corr_prod_rad", np.nan)),
            "DeltaNet": float(row.get("DeltaNet", np.nan)),
        }
    return results


def _old_ac_batch(customers: Dict[str, pd.DataFrame], weather_df: pd.DataFrame) -> Dict[str, dict]:
    """Run old AC feature extraction + pre-trained model on all customers."""
    from ac_actrainingfunctions import (
        FEATURE_COLS,
        AC_PROB_THRESHOLD,
        tot_curve_is_usable,
        extract_tot_features,
    )

    model_path = _REPO / "models" / "ac_detector_v1.joblib"
    if not model_path.exists():
        log.warning("AC model not found at %s — skipping old AC comparison", model_path)
        return {}
    model = joblib.load(model_path)

    # Build per-customer batch rows in the format the old code expects
    w = weather_df[["dt_utc", "t_2m_C", "global_rad_W"]].copy()
    w["dt_utc"] = pd.to_datetime(w["dt_utc"]).astype("datetime64[us]")
    w = w.rename(columns={"t_2m_C": "temp", "global_rad_W": "glob_rad"})

    results = {}
    for cid, df in customers.items():
        try:
            d = df.copy()
            d["DT_UTC"] = pd.to_datetime(d["DT_UTC"], errors="coerce").astype("datetime64[us]")
            d = d.dropna(subset=["DT_UTC"]).sort_values("DT_UTC")
            d = d.rename(columns={"DT_UTC": "dt_utc"})
            d["id_customer"] = cid
            d["type"] = "TOT"
            d["source"] = "validation"
            d["value_kw_mean"] = pd.to_numeric(d["CONSO_KWH"], errors="coerce") * 4.0
            d = pd.merge_asof(d, w, on="dt_utc", direction="backward", tolerance=pd.Timedelta("1h"))
            tot_df = d[d["type"] == "TOT"].copy()
            usable, _, _ = tot_curve_is_usable(tot_df)
            if not usable:
                continue
            feats = extract_tot_features(tot_df)
            if feats is None:
                continue
            X = pd.DataFrame([feats])[FEATURE_COLS].to_numpy(dtype=float)
            proba = model.predict_proba(X)
            classes = model.named_steps["clf"].classes_
            has_ac_idx = int(np.where(classes == 1)[0][0]) if 1 in classes else 0
            prob_ac = float(proba[0, has_ac_idx])
            results[cid] = {"has_ac": bool(prob_ac >= AC_PROB_THRESHOLD), "prob_ac": prob_ac}
        except Exception as exc:
            log.debug("Old AC failed for %s: %s", cid, exc)
    return results


def _old_hp_batch(customers: Dict[str, pd.DataFrame], weather_df: pd.DataFrame) -> Dict[str, dict]:
    """Run old HP feature extraction + pre-trained model on all customers."""
    from hp_detection_functions import (
        FEATURE_COLS,
        INT_TO_LABEL,
        tot_curve_is_usable,
        extract_tot_features,
    )

    model_path = _REPO / "models" / "hp_detector_v1.joblib"
    if not model_path.exists():
        log.warning("HP model not found at %s — skipping old HP comparison", model_path)
        return {}
    model = joblib.load(model_path)

    w = weather_df[["dt_utc", "t_2m_C", "global_rad_W"]].copy()
    w["dt_utc"] = pd.to_datetime(w["dt_utc"]).astype("datetime64[us]")
    w = w.rename(columns={"t_2m_C": "temp", "global_rad_W": "glob_rad"})

    results = {}
    for cid, df in customers.items():
        try:
            d = df.copy()
            d["DT_UTC"] = pd.to_datetime(d["DT_UTC"], errors="coerce").astype("datetime64[us]")
            d = d.dropna(subset=["DT_UTC"]).sort_values("DT_UTC")
            d = d.rename(columns={"DT_UTC": "dt_utc"})
            d["id_customer"] = cid
            d["type"] = "TOT"
            d["source"] = "validation"
            d["value_kw_mean"] = pd.to_numeric(d["CONSO_KWH"], errors="coerce") * 4.0
            d = pd.merge_asof(d, w, on="dt_utc", direction="backward", tolerance=pd.Timedelta("1h"))
            tot_df = d[d["type"] == "TOT"].copy()
            usable, _, _ = tot_curve_is_usable(tot_df)
            if not usable:
                continue
            feats = extract_tot_features(tot_df)
            if feats is None:
                continue
            X = pd.DataFrame([feats])[FEATURE_COLS].to_numpy(dtype=float)
            pred = int(model.predict(X)[0])
            pred_name = INT_TO_LABEL.get(pred, "no_hp")
            proba = model.predict_proba(X)
            classes = model.named_steps["clf"].classes_
            hp_probs = {}
            for cls_id, cls_name in INT_TO_LABEL.items():
                if cls_id in classes:
                    idx = int(np.where(classes == cls_id)[0][0])
                    hp_probs[cls_name] = float(proba[0, idx])
                else:
                    hp_probs[cls_name] = 0.0
            prob_hp = hp_probs.get("winter_hp", 0.0) + hp_probs.get("summer_hp", 0.0)
            results[cid] = {
                "has_hp": pred_name != "no_hp",
                "hp_type": pred_name,
                "prob_hp": prob_hp,
            }
        except Exception as exc:
            log.debug("Old HP failed for %s: %s", cid, exc)
    return results


def _old_battery_per_customer(
    customers: Dict[str, pd.DataFrame],
    weather_df: pd.DataFrame,
    pv_results: Dict[str, dict],
) -> Dict[str, dict]:
    """Run old analyze_battery_residential_v7 per customer."""
    try:
        from battery_detection import analyze_battery_residential_v7
    except ImportError:
        log.warning("battery_detection not importable — skipping old battery comparison")
        return {}

    weather_idx = _weather_indexed(weather_df)
    results = {}
    for cid, df in customers.items():
        pv = pv_results.get(cid, {})
        if not pv.get("has_pv", False):
            results[cid] = {"has_battery": False, "prob_battery": 0.0, "status": "skipped_no_pv"}
            continue
        try:
            d = df.copy()
            d["DT_UTC"] = pd.to_datetime(d["DT_UTC"], errors="coerce")
            d = d.dropna(subset=["DT_UTC"]).set_index("DT_UTC").sort_index()
            pv_row = {
                "pv_capacity_kwp": pv.get("pv_capacity_kwp", 0.0),
                "has_pv": True,
                "has_pv_prob": pv.get("has_pv_prob", np.nan),
            }
            res = analyze_battery_residential_v7(d, weather_idx, pv_row)
            prob_raw = float(res.get("battery_prob", 0.0))
            prob = prob_raw / 100.0 if prob_raw > 1.0 else prob_raw
            results[cid] = {
                "has_battery": prob >= 0.5,
                "prob_battery": prob,
                "status": res.get("status", "ok"),
            }
        except Exception as exc:
            log.debug("Old battery failed for %s: %s", cid, exc)
    return results


