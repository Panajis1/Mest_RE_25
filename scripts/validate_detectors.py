def _load_weather(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Weather cache not found: {path}\nRun the pipeline once first to generate it.")
    df = pd.read_parquet(path)
    for col in ("dt_utc", "t_2m_C", "global_rad_W"):
        if col not in df.columns:
            raise ValueError(f"Weather parquet missing column '{col}'")
    df["dt_utc"] = pd.to_datetime(df["dt_utc"]).astype("datetime64[us]")
    return df.sort_values("dt_utc").reset_index(drop=True)


def _weather_indexed(weather_df: pd.DataFrame) -> pd.DataFrame:
    """Return weather indexed by timestamp (used by old PV + Battery code)."""
    w = weather_df.rename(columns={"dt_utc": "timestamp"}).copy()
    w["timestamp"] = pd.to_datetime(w["timestamp"])
    return w.set_index("timestamp").sort_index()


